const (
	hkdfLabelKeyV1 = "quic key"
	hkdfLabelKeyV2 = "quicv2 key"
	hkdfLabelIVV1  = "quic iv"
	hkdfLabelIVV2  = "quicv2 iv"
	hkdfLabelHPV1  = "quic hp"
	hkdfLabelHPV2  = "quicv2 hp"
)

func initialHDKF(version Version) (salt []byte, keyLabel, ivLabel, hpLabel string) {
	switch version {
	case VersionQ050:
		// Q050
		return saltQ050, hkdfLabelKeyV1, hkdfLabelIVV1, hkdfLabelHPV1
	case VersionT050:
		// T050
		return saltT050, hkdfLabelKeyV1, hkdfLabelIVV1, hkdfLabelHPV1
	case VersionT051:
		// T051
		return saltT051, hkdfLabelKeyV1, hkdfLabelIVV1, hkdfLabelHPV1
	case Version1_Draft17, Version1_Draft18, Version1_Draft19, Version1_Draft20:
		// Draft v1 (17-20)
		return saltV1Draft17, hkdfLabelKeyV1, hkdfLabelIVV1, hkdfLabelHPV1
	case Version1_Draft21, Version1_Draft22:
		// Draft v1 (21-22)
		return saltV1Draft21, hkdfLabelKeyV1, hkdfLabelIVV1, hkdfLabelHPV1
	case Version1_Draft23, Version1_Draft24, Version1_Draft25, Version1_Draft26, Version1_Draft27, Version1_Draft28:
		// Draft v1 (23-28)
		return saltV1Draft23, hkdfLabelKeyV1, hkdfLabelIVV1, hkdfLabelHPV1
	case Version1_Draft29, Version1_Draft30, Version1_Draft31, Version1_Draft32:
		// Draft v1(29-32)
		return saltV1Draft29, hkdfLabelKeyV1, hkdfLabelIVV1, hkdfLabelHPV1
	case Version1_Draft33, Version1_Draft34, Version1:
		// Draft v1 (33-34), IETF QUIC v1
		return saltV1, hkdfLabelKeyV1, hkdfLabelIVV1, hkdfLabelHPV1
	case Version2_Draft0, Version2_Draft1:
		// Draft v2 (01-07)
		return saltV2Draft, hkdfLabelKeyV2, hkdfLabelIVV2, hkdfLabelHPV2
	case Version2:
		// Draft v2 (08-10), IETF QUIC v2
		return saltV2, hkdfLabelKeyV2, hkdfLabelIVV2, hkdfLabelHPV2
	}

	return nil, "", "", ""
}
